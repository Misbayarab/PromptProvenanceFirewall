from .models import (
    DataItem,
    Provenance,
    SourceType,
    TrustLevel
)


def create_user_data(content: str) -> DataItem:
    """
    Create data that came directly from the user.
    User input is considered trusted.
    """

    return DataItem(
        content=content,
        provenance=Provenance(
            source_type=SourceType.USER,
            source_name="user",
            trust_level=TrustLevel.TRUSTED
        )
    )


def create_system_data(content: str) -> DataItem:
    """
    Create data generated by the trusted system.
    """

    return DataItem(
        content=content,
        provenance=Provenance(
            source_type=SourceType.SYSTEM,
            source_name="system",
            trust_level=TrustLevel.TRUSTED
        )
    )


def create_web_data(
    content: str,
    website: str
) -> DataItem:
    """
    Create data obtained from a website.

    Website content is treated as untrusted because
    external webpages may contain malicious instructions.
    """

    return DataItem(
        content=content,
        provenance=Provenance(
            source_type=SourceType.WEBSITE,
            source_name=website,
            trust_level=TrustLevel.UNTRUSTED
        )
    )


